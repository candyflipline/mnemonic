CREATE VIEW moraine.v_all_events
(
    `ingested_at` DateTime64(3),
    `event_uid` String,
    `compacted_parent_uid` String,
    `session_id` String,
    `session_date` Date,
    `source_file` String,
    `source_inode` UInt64,
    `source_generation` UInt32,
    `source_line_no` UInt64,
    `source_offset` UInt64,
    `source_ref` String,
    `record_ts` String,
    `event_class` LowCardinality(String),
    `payload_type` LowCardinality(String),
    `actor_role` LowCardinality(String),
    `turn_id` String,
    `item_id` String,
    `call_id` String,
    `name` LowCardinality(String),
    `phase` String,
    `text_content` String,
    `payload_json` String,
    `token_usage_json` String,
    `endpoint_kind` LowCardinality(String),
    `token_usage_buckets` Map(String, UInt64),
    `token_usage_native_units` Map(String, Float64),
    `event_version` UInt64
)
AS SELECT
    ingested_at,
    event_uid,
    origin_event_id AS compacted_parent_uid,
    session_id,
    session_date,
    source_file,
    source_inode,
    source_generation,
    source_line_no,
    source_offset,
    source_ref,
    record_ts,
    event_kind AS event_class,
    payload_type,
    actor_kind AS actor_role,
    toString(turn_index) AS turn_id,
    item_id,
    tool_call_id AS call_id,
    tool_name AS name,
    if(tool_phase != '', tool_phase, op_status) AS phase,
    text_content,
    payload_json,
    token_usage_json,
    endpoint_kind,
    token_usage_buckets,
    token_usage_native_units,
    event_version
FROM moraine.events
FINAL
