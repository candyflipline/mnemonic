// genschema writes internal/schema/events.go from docs/clickhouse/events.tsv,
// the column list of ClickHouse moraine_personal.events (name<TAB>type).
//
//	go run ./scripts/genschema
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// Lake-only columns the normalizer never emits: the lake writer stamps
// ingested_at, and author belongs to the shared ClickHouse only.
var skip = map[string]bool{"ingested_at": true, "author": true}

type mapping struct{ goType, duckType string }

var types = map[string]mapping{
	"String":                 {"string", "VARCHAR"},
	"LowCardinality(String)": {"string", "VARCHAR"},
	"DateTime64(3)":          {"string", "TIMESTAMP"},
	"Date":                   {"string", "DATE"},
	"UInt8":                  {"uint8", "UTINYINT"},
	"UInt16":                 {"uint16", "USMALLINT"},
	"UInt32":                 {"uint32", "UINTEGER"},
	"UInt64":                 {"uint64", "UBIGINT"},
	"Array(String)":          {"[]string", "VARCHAR[]"},
	"Map(String, UInt64)":    {"map[string]uint64", "MAP(VARCHAR, UBIGINT)"},
	"Map(String, Float64)":   {"map[string]float64", "MAP(VARCHAR, DOUBLE)"},
}

func main() {
	f, err := os.Open("docs/clickhouse/events.tsv")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	var cols, fields bytes.Buffer
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		name, chType, ok := strings.Cut(sc.Text(), "\t")
		if !ok || skip[name] {
			continue
		}
		m, ok := types[chType]
		if !ok {
			log.Fatalf("column %s: unmapped ClickHouse type %q; add it to genschema's types table", name, chType)
		}
		fmt.Fprintf(&cols, "\t{%q, %q, %q},\n", name, chType, m.duckType)
		fmt.Fprintf(&fields, "\t%s %s `json:%q`\n", goName(name), m.goType, name)
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}

	src := fmt.Sprintf(`// Code generated by scripts/genschema from docs/clickhouse/events.tsv. DO NOT EDIT.

package schema

// Column is one events column: its ClickHouse type and the DuckDB type the
// lake and cache use for it.
type Column struct {
	Name, ClickHouse, DuckDB string
}

// EventColumns are the columns every parser fills, in ClickHouse order.
// DateTime64(3) values are "2006-01-02 15:04:05.000" UTC strings and Date
// values "2006-01-02", exactly as the golden fixtures carry them.
var EventColumns = []Column{
%s}

// Event is one normalized event row.
type Event struct {
%s}
`, cols.String(), fields.String())

	out, err := format.Source([]byte(src))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("internal/schema/events.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func goName(col string) string {
	var b strings.Builder
	for _, part := range strings.Split(col, "_") {
		switch part {
		case "id", "uid", "ts", "json":
			b.WriteString(strings.ToUpper(part))
		default:
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}
